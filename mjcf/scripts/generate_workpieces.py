# -*- coding: utf-8 -*-
"""在两个物料框（StorageCage_B / StorageCage_I）内各随机摆放 5 个工件，
生成 MuJoCo body 定义并写回 luna_m6_props.xml 的标记块。

用法（在 mjcf 目录下）：
    python scripts/generate_workpieces.py            # 默认种子 20260921
    python scripts/generate_workpieces.py --seed 7   # 换一批随机布局

摆放规则：
  * 一层平铺，工件底面贴合框底板上表面（局部 z = 0.085），初始再抬 2 mm 让其自然落稳；
  * 随机位置 + 随机绕 z 偏航，任意朝向都完整落在框内：
      - 不与四周围板（内表面 ±0.342，与视觉侧壁对齐）相交；
      - 不与四角立柱（内表面 ±0.35）相交；
  * 两两之间用 OBB 分离轴检测，保证不重叠（留 5 mm 间隙）。

工件局部坐标系：原点 = 底面中心，z 向上（见 assets/meshes 里工件资产的规范化说明）。
"""
import argparse
import json
import math
import os
import random
import re
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
MJCF_DIR = os.path.dirname(HERE)
PROPS = os.path.join(MJCF_DIR, "luna_m6_props.xml")
MESH_FILE = "assets/meshes/Workpiece_S01_162x162x63.STL"
MESH_NAME = "Workpiece_S01"

BEGIN = "<!-- ===== WORKPIECES BEGIN (generated by scripts/generate_workpieces.py) ===== -->"
END = "<!-- ===== WORKPIECES END ===== -->"

# ---------------- 工件几何（米，与规范化导出的 STL 一致） ----------------
# 工件外形是圆盘：直径 161.768 mm，高 63.496 mm（STL 的 AABB 是其外接正方形）
WP_R = 0.161768 / 2.0       # 0.080884，圆盘半径
WP_HZ = 0.063496 / 2.0      # 0.031748，半高
WP_TOP = 0.063496           # 工件总高

# ---------------- 物料框内腔（框局部坐标：原点=底面中心，z 向上） ----------------
FLOOR_TOP = 0.085           # 底板上表面 z（collision_Cage_*_Floor: pos z=0.06, half 0.025）
POST_INNER = 0.350          # 四角立柱内表面（Post: pos ±0.375, half 0.025）
# 四周围板内表面。必须与「视觉网格」对齐：实测 StorageCage STL 的侧壁
# （下部实心板 + 上部钢丝网）位于 |x|,|y| = 0.3455 .. 0.3505，立柱内缘 0.350。
# props.xml 里围板放在 ±0.348（半厚 0.006 → 内表面 0.342），比视觉内表面再内收
# 3.5 mm，工件边缘因此不会插进视觉网格（原先 ±0.372 会外扩 20 mm 造成穿模）。
WALL_INNER = 0.342
POST_OUTER = 0.400

CAGE_BASE_Z = 0.0   # 框底面高度：地面在 z=0，与 luna_m6_props.xml 中
                    # StorageCage_B / StorageCage_I 的 pos.z 保持一致
CAGES = {
    "B": np.array([-4.0, 1.2, CAGE_BASE_Z]),
    "I": np.array([-5.0, 1.2, CAGE_BASE_Z]),
}
N_PER_CAGE = 5
GAP = 0.005                 # 工件之间最小间隙
DROP_LIFT = 0.5          # 初始抬升量，落下后贴框底

# ---------------- 接触参数（针对「拖动抖动 / 穿模」调优） ----------------
# condim：默认 3 只有法向 + 2 个切向摩擦，friction 里后两个数（扭转 / 滚动）
#   完全不生效。工件是圆盘，被拖动后会自转，必须启用扭转摩擦才能耗散掉 ——
#   因此用 6（法向 + 2 切向 + 扭转 + 2 滚动）。
CONDIM = 6
# 第 1 个数（滑动摩擦）调到 0.9 让拖动后更快停住；
# 后两个（扭转 / 滚动，单位是长度）保持常规金属值。
FRICTION = "0.9 0.02 0.005"
# 接触余量：让接触在几何接触前 0.3 mm 就建立，避免高速拖动瞬间压穿框壁、
#   也消除「接触突然出现/消失」造成的抖动。
#   注意 MuJoCo 的软接触会在 margin 距离内开始产生支撑力，工件因此会"悬浮"
#   在底板上 margin 高 —— 0.001 时实测悬空 0.97 mm（对抓取仿真偏大），
#   收到 0.0003 后悬浮仅 0.3 mm，肉眼不可见。
MARGIN = 0.0003

# ---------------- 质量 / 惯性（按实体体积 + 铝合金密度估算） ----------------
SOLID_VOLUME_M3 = 0.0005305213   # 减面网格实测实体体积
DENSITY_KG_M3 = 2700.0           # 铝合金；改铸铁用 7200
MASS = SOLID_VOLUME_M3 * DENSITY_KG_M3
# 实心圆柱惯性（碰撞体即等尺寸圆柱；工件带中心孔，真实 Izz 略大于此值，工程上够用）
I_XX = MASS / 12.0 * (3.0 * WP_R ** 2 + WP_HZ ** 2)
I_YY = I_XX
I_ZZ = MASS / 2.0 * WP_R ** 2


def rect_corners(cx, cy, yaw, hx, hy):
    c, s = math.cos(yaw), math.sin(yaw)
    return np.array([
        [cx + (-hx) * c - (-hy) * s, cy + (-hx) * s + (-hy) * c],
        [cx + (hx) * c - (-hy) * s, cy + (hx) * s + (-hy) * c],
        [cx + (hx) * c - (hy) * s, cy + (hx) * s + (hy) * c],
        [cx + (-hx) * c - (hy) * s, cy + (-hx) * s + (hy) * c],
    ])


def sat_overlap(p1, p2):
    """分离轴定理：两个凸多边形是否重叠。"""
    for poly in (p1, p2):
        n = len(poly)
        for i in range(n):
            edge = poly[(i + 1) % n] - poly[i]
            axis = np.array([-edge[1], edge[0]])
            ln = np.linalg.norm(axis)
            if ln < 1e-12:
                continue
            axis = axis / ln
            a, b = p1 @ axis, p2 @ axis
            if a.max() < b.min() or b.max() < a.min():
                return False
    return True


def inside_cage(poly):
    """工件的四个角点必须完整位于框内（围板内、且避开四角立柱）。"""
    if np.abs(poly).max() > WALL_INNER:
        return False
    mn, mx = poly.min(axis=0), poly.max(axis=0)
    for sx in (1, -1):
        for sy in (1, -1):
            px_min = POST_INNER if sx > 0 else -POST_OUTER
            px_max = POST_OUTER if sx > 0 else -POST_INNER
            py_min = POST_INNER if sy > 0 else -POST_OUTER
            py_max = POST_OUTER if sy > 0 else -POST_INNER
            if mx[0] > px_min and px_max > mn[0] and mx[1] > py_min and py_max > mn[1]:
                return False
    return True


def sample_layout(n, rng, max_tries=400000):
    """序贯随机放置（RSA）：随机位置 + 随机偏航，直到放下 n 个。

    间距用圆盘外接正方形（保守，圆盘与圆盘不相交则外接方形也不相交）。"""
    placed = []
    hx = WP_R + GAP / 2.0
    hy = WP_R + GAP / 2.0
    tries = 0
    while len(placed) < n:
        tries += 1
        if tries > max_tries:
            raise RuntimeError(
                "框内随机摆放失败（尝试 %d 次只放下 %d/%d 个）。"
                "可减小 GAP、放宽 DROP_LIFT，或减少每框工件数。" % (tries, len(placed), n))
        yaw = rng.uniform(0.0, 2.0 * math.pi)
        c, s = abs(math.cos(yaw)), abs(math.sin(yaw))
        aabb_hx = hx * c + hy * s
        aabb_hy = hx * s + hy * c
        # 中心采样范围：保证 AABB 落在围板内（角立柱由 inside_cage 再筛）
        lim = WALL_INNER
        rx, ry = lim - aabb_hx, lim - aabb_hy
        if rx <= 0 or ry <= 0:
            continue
        cx = rng.uniform(-rx, rx)
        cy = rng.uniform(-ry, ry)
        poly = rect_corners(cx, cy, yaw, hx, hy)
        if not inside_cage(poly):
            continue
        if any(sat_overlap(poly, rect_corners(pcx, pcy, pyaw, hx, hy))
               for (pcx, pcy, pyaw) in placed):
            continue
        placed.append((cx, cy, yaw))
    return placed, tries


def xml_float(v):
    return ("%.6f" % v).rstrip("0").rstrip(".") if abs(v) > 1e-9 else "0"


def build_block(seed):
    rng = random.Random(seed)
    lines = [BEGIN]
    lines.append("    <!--")
    lines.append("      工件（铸件 s01，减面到 25%%。每个物料框内随机平铺 %d 个，共 %d 个。" % (N_PER_CAGE, N_PER_CAGE * 2))
    lines.append("      由 scripts/generate_workpieces.py 生成，改种子重跑即可换一批布局。")
    lines.append("")
    lines.append("      几何/物理约定：")
    lines.append("        * 工件网格原点在「底面中心」，z 向上平放，所以 body 的 pos.z 直接就是工件底面高度；")
    lines.append("        * 底面贴框底板上表面（框局部 z=%.3f），初始抬 %.0f mm 让其自然落稳；" % (FLOOR_TOP, DROP_LIFT * 1000))
    lines.append("        * 外观用减面网格（%d 面）；工件是直径 %.1f mm 的圆盘，碰撞用等尺寸圆柱体，" % (12246, WP_R * 2000))
    lines.append("          比外接盒体贴合得多，抓取仿真时不会提前碰上 —— 与项目 link / 道具用近似体的做法一致；")
    lines.append("        * 接触体带 condim=\"%d\" friction=\"%s\" margin=\"%s\"：" % (CONDIM, FRICTION, xml_float(MARGIN)))
    lines.append("          condim=6 才让扭转/滚动摩擦真正生效（默认 condim=3 时 friction 后两个数无效），")
    lines.append("          圆盘被拖动后能迅速停稳；margin 让接触提前 %.1f mm 建立，拖动时不易压穿框壁" % (MARGIN * 1000))
    lines.append("          （代价是工件在底板上会悬浮同样的距离，0.3 mm 肉眼不可见）。")
    lines.append("        * 质量按实体体积 %.4f m^3 x %.0f kg/m^3（铝）估算 = %.3f kg，惯性按等尺寸实心圆柱；" % (SOLID_VOLUME_M3, DENSITY_KG_M3, MASS))
    lines.append("          若工件实为铸铁，把 mass 改成 %.3f、diaginertia 乘以 %.2f 即可。" % (SOLID_VOLUME_M3 * 7200.0, 7200.0 / DENSITY_KG_M3))
    lines.append("        * freejoint 让它们可被机器人抓取/碰撞推动。")
    lines.append("    -->")

    stats = []
    for tag, base in CAGES.items():
        placed, tries = sample_layout(N_PER_CAGE, rng)
        lines.append("")
        lines.append("    <!-- 物料框 %s：%s -->" % (
            tag, "工艺说明见上" if tag == "B" else "与 %s 同规格、同摆放规则" % "B"))
        for i, (cx, cy, yaw) in enumerate(placed, start=1):
            wx = base[0] + cx
            wy = base[1] + cy
            wz = base[2] + FLOOR_TOP + DROP_LIFT
            qw = math.cos(yaw / 2.0)
            qz = math.sin(yaw / 2.0)
            name = "Workpiece_%s_%d" % (tag, i)
            lines.append('    <body name="%s" pos="%s %s %s" quat="%s 0 0 %s">' % (
                name, xml_float(wx), xml_float(wy), xml_float(wz), xml_float(qw), xml_float(qz)))
            lines.append('      <freejoint name="free_%s"/>' % name)
            lines.append('      <inertial pos="0 0 %s" mass="%s" diaginertia="%s %s %s"/>' % (
                xml_float(WP_HZ), round(MASS, 4), round(I_XX, 6), round(I_YY, 6), round(I_ZZ, 6)))
            lines.append('      <geom name="visual_%s" type="mesh" mesh="%s" pos="0 0 0" quat="1 0 0 0"'
                         ' rgba="0.82 0.83 0.86 1" contype="0" conaffinity="0" group="1"/>' % (name, MESH_NAME))
            lines.append('      <geom name="collision_%s" type="cylinder" pos="0 0 %s" size="%s %s"'
                         ' contype="1" conaffinity="1" group="3"'
                         ' condim="%d" friction="%s" margin="%s"/>' % (
                             name, xml_float(WP_HZ), xml_float(WP_R), xml_float(WP_HZ),
                             CONDIM, FRICTION, xml_float(MARGIN)))
            lines.append('    </body>')
            stats.append({
                "body": name, "cage": tag,
                "local_x": round(cx, 4), "local_y": round(cy, 4),
                "yaw_deg": round(math.degrees(yaw) % 360.0, 1),
                "world_pos": [round(wx, 4), round(wy, 4), round(wz, 4)],
            })
        lines.append("    <!-- 框 %s：%d 次随机尝试放下 %d 个工件 -->" % (tag, tries, len(placed)))
    lines.append(END)
    return "\n".join(lines), stats


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=20230111)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    block, stats = build_block(args.seed)

    with open(PROPS, "r", encoding="utf-8") as f:
        text = f.read()

    if BEGIN in text and END in text:
        new_text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), block, text, flags=re.S)
        mode = "replaced marker block"
    else:
        raise SystemExit("未找到标记块，请先在 luna_m6_props.xml 的 <worldbody> 内插入：\n%s\n%s" % (BEGIN, END))

    if not args.dry_run:
        with open(PROPS, "w", encoding="utf-8", newline="\n") as f:
            f.write(new_text)

    print(json.dumps({
        "props": PROPS,
        "seed": args.seed,
        "mode": mode,
        "dry_run": args.dry_run,
        "count": len(stats),
        "mass_kg": round(MASS, 4),
        "diaginertia": [round(I_XX, 6), round(I_YY, 6), round(I_ZZ, 6)],
        "workpieces": stats,
    }, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
